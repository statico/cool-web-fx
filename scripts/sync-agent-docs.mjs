// Keep the hand-written agent docs in sync with src/demos/*.json.
//
// public/llms.txt and public/skill.md both carry a list of every effect. Those
// lists had already drifted (nell-text-warp was missing from both), so the
// generated regions are fenced with `a14y:begin effects` / `a14y:end effects`
// and rebuilt from the demo metadata. Prose outside the fences is left alone.
//
//   node scripts/sync-agent-docs.mjs          # rewrite the fenced regions
//   node scripts/sync-agent-docs.mjs --check  # exit 1 if either file is stale

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');

const BEGIN = '<!-- a14y:begin effects — generated by scripts/sync-agent-docs.mjs -->';
const END = '<!-- a14y:end effects -->';

const demos = fs
  .readdirSync(path.join(ROOT, 'src/demos'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(fs.readFileSync(path.join(ROOT, 'src/demos', f), 'utf-8')))
  .sort((a, b) => (a.order ?? 999) - (b.order ?? 999));

const llmsList = demos
  .map((d) => `- ${d.slug}: ${d.blurb} — seen on ${d.sourceUrl} — /effects/${d.slug}.html`)
  .join('\n');

const skillTable = [
  '| slug | what it is | seen on |',
  '|------|------------|---------|',
  ...demos.map((d) => `| \`${d.slug}\` | ${d.blurb} | ${d.sourceUrl} |`),
].join('\n');

function replaceFence(file, body) {
  const p = path.join(ROOT, file);
  const src = fs.readFileSync(p, 'utf-8');
  const bi = src.indexOf(BEGIN);
  if (bi === -1) throw new Error(`${file}: missing ${BEGIN}`);
  const ei = src.indexOf(END, bi);
  if (ei === -1) throw new Error(`${file}: missing closing fence`);
  const next = `${src.slice(0, bi)}${BEGIN}\n${body}\n${END}${src.slice(ei + END.length)}`;
  if (next === src) return false;
  if (!CHECK) fs.writeFileSync(p, next);
  return true;
}

const stale = [
  ['public/llms.txt', llmsList],
  ['public/skill.md', skillTable],
].filter(([file, body]) => replaceFence(file, body));

if (CHECK) {
  if (stale.length) {
    console.error(`sync-agent-docs: stale — ${stale.map(([f]) => f).join(', ')}`);
    console.error('Run: node scripts/sync-agent-docs.mjs');
    process.exit(1);
  }
  console.log('sync-agent-docs: llms.txt and skill.md are up to date');
} else {
  console.log(
    stale.length
      ? `sync-agent-docs: updated ${stale.map(([f]) => f).join(', ')}`
      : 'sync-agent-docs: already up to date',
  );
}
